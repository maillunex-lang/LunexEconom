def catalog():
    return [{"id": k, "title": v["title"], "hint": v["hint"]} for k, v in TYPES.items()]


def starter_plan(type_id, name, repo=""):
    t = TYPES.get(type_id)
    if t is None:
        raise KeyError("unknown_type")
    return {"project": {"name": name, "repo": repo or "репозиторий проекта", "branch": "main"}, "updated": "2026-01-01", "rules": copy.deepcopy(RULES),
            "lanes": copy.deepcopy(t["lanes"]), "packages": [_pkg(*p) for p in t["packages"]]}


def gdd_outline(name):
    return GDD_OUTLINE.format(name=name)


def as_json(type_id, name, repo=""):
    return json.dumps(starter_plan(type_id, name, repo), ensure_ascii=False, indent=1) + "\n"
