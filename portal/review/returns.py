"""Шаблоны возврата на доработку: типовые замечания одним нажатием и готовый промпт доработки."""
from __future__ import annotations

TEMPLATES = {
    "no_tests": ("Нет тестов", "Добавь тесты на новую логику (успешный путь, ошибки, граничные случаи). Все существующие тесты должны проходить."),
    "out_of_zone": ("Вышел за зону файлов", "Ты изменил файлы вне разрешённой зоны. Верни их в исходное состояние (git checkout origin/main -- путь) и оставь только файлы своей зоны. Общие файлы директора не менять."),
    "ci_red": ("CI красный", "CI на PR не проходит. Прочитай лог упавшего прогона, исправь причину (не отключай и не пропускай тесты) и запушь исправление в ту же ветку."),
    "secrets": ("Секреты в коде", "В диффе есть похожее на секрет. Удали значение из кода и истории PR (новый коммит недостаточно, если секрет реальный: сообщи владельцу), используй чтение из файла или переменную окружения."),
    "too_big": ("PR слишком большой", "PR слишком большой для проверки. Выдели лишнее в отдельный PR или сократи изменения до цели задания."),
    "no_report": ("Нет отчёта", "Добавь отчёт в указанный файл qa: что сделано, какие проверки прошли (с цифрами), допущения и ограничения."),
    "conflicts": ("Конфликт с main", "Влей свежий main в свою ветку, разреши конфликты без потери чужих изменений, перезапусти все проверки и запушь."),
    "not_done": ("Не выполнены критерии", "Не все критерии готовности выполнены. Пройди по списку «done_when» задания и закрой каждый пункт, затем отметь это в отчёте."),
    "security": ("Ослаблена безопасность", "Изменение ослабляет защиту (проверки, CSRF, лимиты, права, подпись). Верни защиту к прежнему уровню; новые возможности должны быть выключены по умолчанию."),
}


def catalog():
    return [{"id": k, "title": v[0], "text": v[1]} for k, v in TEMPLATES.items()]


def rework_prompt(task_id, task_title, reason_ids, note="", pr_url="", attempt=1):
    reasons = [r for r in reason_ids if r in TEMPLATES]
    if not reasons and not note.strip():
        raise ValueError("no_reasons")
    lines = ["Доработка задания %s: %s." % (task_id, task_title)]
    if pr_url:
        lines.append("Pull request: %s (работай в той же ветке, новый PR не создавай)." % pr_url)
    lines.append("Попытка доработки: %d. Исправь только перечисленное, остальное не ломай." % attempt)
    lines.append("")
    lines.append("Замечания директора:")
    for i, r in enumerate(reasons, 1):
        lines.append("%d. %s: %s" % (i, TEMPLATES[r][0], TEMPLATES[r][1]))
    if note.strip():
        lines.append("%d. Дополнительно: %s" % (len(reasons) + 1, note.strip()[:1500]))
    lines += ["", "После исправления: все тесты зелёные, CI зелёный, обнови отчёт (что исправлено), сообщи SHA последнего коммита."]
    return "\n".join(lines)


def reasons_from_review(v):
    """Подсказка: какие шаблоны предложить по красным и жёлтым пунктам светофора."""
    mapping = {"zone": "out_of_zone", "secrets": "secrets", "ci": "ci_red", "size": "too_big", "tests_added": "no_tests", "report": "no_report", "checklist": "not_done"}
    return [mapping[c["id"]] for c in v.get("checks", []) if c["status"] != "green" and c["id"] in mapping]
