"""Authoritative, immutable and validated catalog for the V2 game economy."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from jsonschema import Draft202012Validator

ROOT = Path(__file__).resolve().parents[1] / 'data'
NAMES = ('products', 'recipes', 'buildings')
_ACTIVE_RUNTIME = None  # catalog revision for legacy Catalog() readers


class CatalogError(ValueError):
    """A startup-blocking catalog inconsistency with an actionable explanation."""


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False).encode('utf-8')


def load_all(root=None):
    root = Path(root) if root is not None else ROOT
    try:
        schema = json.loads((root / 'schema.json').read_text(encoding='utf-8'), parse_constant=lambda v: (_ for _ in ()).throw(ValueError(v)))
        Draft202012Validator.check_schema(schema)
        result = {}
        for name in NAMES:
            # Reject duplicate JSON object keys rather than silently accepting the last entry.
            def unique_pairs(pairs):
                item = {}
                for key, value in pairs:
                    if key in item:
                        raise CatalogError(f'{name}: duplicate JSON key {key!r}')
                    item[key] = value
                return item
            contents = json.loads((root / (name + '.json')).read_text(encoding='utf-8'), object_pairs_hook=unique_pairs, parse_constant=lambda v: (_ for _ in ()).throw(ValueError(v)))
            errors = list(Draft202012Validator(schema['$defs'][name]).iter_errors(contents))
            if errors:
                err = sorted(errors, key=lambda e: str(e.path))[0]
                raise CatalogError(f'{name}{list(err.path)}: {err.message}')
            ids = [item['id'] for item in contents]
            if len(ids) != len(set(ids)):
                raise CatalogError(f'{name}: duplicate id(s)')
            result[name] = contents
        verify(result)
        return result
    except CatalogError:
        raise
    except (OSError, KeyError, ValueError, TypeError) as exc:
        raise CatalogError(f'Failed to load catalog in {root}: {exc}') from exc


def verify(data):
    products = {p['id']: p for p in data['products']}
    buildings = {b['id']: b for b in data['buildings']}
    recipes = data['recipes']
    if not products or not buildings or not recipes:
        raise CatalogError('Catalog must not be empty')
    for p in products.values():
        if p['quality_range']['min'] > p['quality_range']['max']:
            raise CatalogError(f"{p['id']}: quality_range min exceeds max")
        if sum(p['rating_weights'].values()) != 100:
            raise CatalogError(f"{p['id']}: rating weights must total 100")
    graph = {p: set() for p in products}
    by_building = {}
    producers = set()
    for recipe in recipes:
        bid = recipe['building']
        if bid not in buildings:
            raise CatalogError(f"Recipe {recipe['id']}: unknown building {bid}")
        b = buildings[bid]
        if not b['production']:
            raise CatalogError(f"Recipe {recipe['id']}: {bid} is not a producer")
        if recipe['workers'] > b['jobs']:
            raise CatalogError(f"Recipe {recipe['id']}: workers exceed jobs in {bid}")
        by_building.setdefault(bid, []).append(recipe)
        for kind in ('inputs', 'outputs'):
            for product in recipe[kind]:
                if product not in products:
                    raise CatalogError(f"Recipe {recipe['id']}: unknown {kind} product {product}")
                if kind == 'outputs':
                    producers.add(product)
        for source in recipe['inputs']:
            for target in recipe['outputs']:
                graph[source].add(target)
    for b in buildings.values():
        if b['production'] and b['id'] not in by_building:
            raise CatalogError(f"Producing building {b['id']} has no recipe")
        if b['role'] == 'retail':
            for product in b.get('allowed_goods', []):
                if product not in products:
                    raise CatalogError(f"Retail building {b['id']}: unknown product {product}")
    # Source inputs may be mined/harvested from external reserves later, but any
    # processed product used by a recipe must be generated by a known producer.
    for recipe in recipes:
        for p in recipe['inputs']:
            if p not in producers:
                raise CatalogError(f"Recipe {recipe['id']}: input {p} has no producer")
    visiting, visited = set(), set()
    def visit(node):
        if node in visiting:
            raise CatalogError(f'Production cycle detected at {node}')
        if node in visited:
            return
        visiting.add(node)
        for nxt in sorted(graph[node]):
            visit(nxt)
        visiting.remove(node)
        visited.add(node)
    for node in sorted(graph):
        visit(node)
    for building, input_id, output_id in [('field', None, 'grain'), ('mill', 'grain', 'flour'), ('bakery', 'flour', 'bread')]:
        if not any(output_id in r['outputs'] and (input_id is None or input_id in r['inputs']) for r in by_building.get(building, [])):
            raise CatalogError(f'M1 broken: {building} must produce {output_id} from {input_id}')
    if not any('bread' in b.get('allowed_goods', []) and b.get('retail_cells', 0) > 0 for b in buildings.values() if b['role'] == 'retail'):
        raise CatalogError('M1 broken: no shop selling bread')
    if not any(products[p]['consumer'] for p in products):
        raise CatalogError('Catalog contains no consumer goods')


class Catalog:
    def __init__(self, root=None):
        # All no-argument Catalog readers see the latest committed runtime
        # snapshot; explicit-root callers remain isolated for schema tests.
        if root is None and _ACTIVE_RUNTIME is not None:
            self.__dict__ = _ACTIVE_RUNTIME.__dict__
            return
        self.data = load_all(root)
        self.version = hashlib.sha256(canonical(self.data)).hexdigest()
        self.etag = '"' + self.version + '"'
        self.index = {name: {item['id']: item for item in self.data[name]} for name in NAMES}
        self.payload = {**self.data, 'version': self.version, 'balance': 'draft'}


def load(name):
    if name not in NAMES:
        raise ValueError('Unknown catalog')
    return load_all()[name]


def migrations():
    return []


def register(registry):
    # Building a new WSGI registry must not inherit an earlier app's runtime.
    global _ACTIVE_RUNTIME
    _ACTIVE_RUNTIME = None
    # Eager validation intentionally blocks app startup even before database access.
    catalog = Catalog()

    def collection(body, context):
        raw_tag = context.get('if_none_match', '')
        matches = [tag.strip() for tag in raw_tag.split(',')]
        if catalog.etag in matches or '*' in matches:
            return 304, {}
        return 200, catalog.payload

    def item(kind, ident):
        def handler(body, context):
            item_value = catalog.index[kind].get(ident)
            return (200, item_value) if item_value is not None else (404, {'error': 'not_found'})
        return handler

    registry.route('GET', '/catalog', collection)
    # The current Registry uses exact paths, not path patterns. Pre-register the
    # immutable set of known IDs and use one safe generic handler for unknown IDs.
    for kind in ('products', 'buildings'):
        for ident in catalog.index[kind]:
            registry.route('GET', f'/catalog/{kind}/{ident}', item(kind, ident))
    registry.catalog = catalog
