"""PostgreSQL persistence for LunexEconom. No external database access."""
import os
from pathlib import Path
import psycopg

def connect():
    password_file = Path(os.environ.get("LUNEX_PG_PASSWORD_FILE", "/home/gamedev/projects/LunexEconom-server/secrets/postgres-password"))
    password = password_file.read_text().strip()
    return psycopg.connect(host="127.0.0.1", port=15439, dbname=os.environ.get("LUNEX_PG_DB", "lunexeconom"),
                           user="lunexeconom", password=password, connect_timeout=5)

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username TEXT UNIQUE NOT NULL, email TEXT UNIQUE NOT NULL,
 salt BYTEA NOT NULL, password_hash BYTEA NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS buildings (
 id TEXT PRIMARY KEY, owner TEXT NOT NULL, kind TEXT NOT NULL,
 x INTEGER NOT NULL, y INTEGER NOT NULL, created BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS cells (
 x INTEGER NOT NULL, y INTEGER NOT NULL, object_id TEXT NOT NULL REFERENCES buildings(id),
 PRIMARY KEY(x,y)
);
CREATE TABLE IF NOT EXISTS chunks (
 cx INTEGER NOT NULL, cy INTEGER NOT NULL, version INTEGER NOT NULL,
 PRIMARY KEY(cx,cy)
);
CREATE TABLE IF NOT EXISTS events (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cx INTEGER NOT NULL, cy INTEGER NOT NULL, version INTEGER NOT NULL,
 kind TEXT NOT NULL, payload TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS roads (
 x INTEGER NOT NULL, y INTEGER NOT NULL, owner TEXT NOT NULL, created BIGINT NOT NULL,
 PRIMARY KEY(x,y)
);
CREATE TABLE IF NOT EXISTS wallets (account TEXT PRIMARY KEY, balance BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS ledger_tx (id TEXT PRIMARY KEY, kind TEXT NOT NULL, memo TEXT NOT NULL, created BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS ledger_entries (
 tx_id TEXT NOT NULL REFERENCES ledger_tx(id), account TEXT NOT NULL, amount BIGINT NOT NULL,
 PRIMARY KEY(tx_id, account)
);
CREATE TABLE IF NOT EXISTS world_clock (id INTEGER PRIMARY KEY, epoch BIGINT NOT NULL, month_seconds BIGINT NOT NULL, base_index BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS building_ops (object_id TEXT PRIMARY KEY, owner TEXT NOT NULL, kind TEXT NOT NULL, start_month BIGINT NOT NULL, start_permille INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS market_prices (product TEXT NOT NULL, month_index BIGINT NOT NULL, price BIGINT NOT NULL, supply BIGINT NOT NULL, demand BIGINT NOT NULL, PRIMARY KEY(product, month_index));
CREATE TABLE IF NOT EXISTS company_state (owner TEXT PRIMARY KEY, settled_through BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS monthly_reports (owner TEXT NOT NULL, month_index BIGINT NOT NULL, revenue BIGINT NOT NULL, upkeep BIGINT NOT NULL, profit BIGINT NOT NULL, buildings INTEGER NOT NULL, PRIMARY KEY(owner, month_index));
CREATE TABLE IF NOT EXISTS commands (
 owner TEXT NOT NULL, request_id TEXT NOT NULL, response TEXT NOT NULL,
 PRIMARY KEY(owner,request_id)
);
"""

def init():
    with connect() as db:
        for statement in SCHEMA.split(";"):
            if statement.strip():
                db.execute(statement)
        db.commit()
