"""PostgreSQL persistence for LunexEconom. No external database access."""
import os
from pathlib import Path
import psycopg

def connect():
    password_file = Path(os.environ.get("LUNEX_PG_PASSWORD_FILE", "/home/gamedev/projects/LunexEconom-server/secrets/postgres-password"))
    # CI uses an isolated PostgreSQL 16 service; production keeps its secret file.
    password = os.environ.get("LUNEX_PG_PASSWORD")
    if password is None:
        password = password_file.read_text().strip()
    return psycopg.connect(host=os.environ.get("LUNEX_PG_HOST", "127.0.0.1"),
                           port=int(os.environ.get("LUNEX_PG_PORT", "15439")),
                           dbname=os.environ.get("LUNEX_PG_DB", "lunexeconom"),
                           user=os.environ.get("LUNEX_PG_USER", "lunexeconom"),
                           password=password, connect_timeout=5)

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username TEXT UNIQUE NOT NULL, email TEXT UNIQUE NOT NULL,
 salt BYTEA NOT NULL, password_hash BYTEA NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS buildings (
 id TEXT PRIMARY KEY, owner TEXT NOT NULL, kind TEXT NOT NULL,
 x INTEGER NOT NULL, y INTEGER NOT NULL, created BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS building_dimensions (
 object_id TEXT PRIMARY KEY REFERENCES buildings(id) ON DELETE CASCADE,
 width INTEGER NOT NULL CHECK(width BETWEEN 1 AND 3),
 height INTEGER NOT NULL CHECK(height BETWEEN 1 AND 3),
 equipment_level INTEGER NOT NULL DEFAULT 1 CHECK(equipment_level BETWEEN 1 AND 3)
);
CREATE TABLE IF NOT EXISTS building_specializations (
 object_id TEXT PRIMARY KEY REFERENCES buildings(id) ON DELETE CASCADE,
 specialization TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS cells (
 x INTEGER NOT NULL, y INTEGER NOT NULL, object_id TEXT NOT NULL REFERENCES buildings(id),
 PRIMARY KEY(x,y)
);
CREATE TABLE IF NOT EXISTS chunks (
 cx INTEGER NOT NULL, cy INTEGER NOT NULL, version INTEGER NOT NULL,
 PRIMARY KEY(cx,cy)
);
CREATE TABLE IF NOT EXISTS events (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cx INTEGER NOT NULL, cy INTEGER NOT NULL, version INTEGER NOT NULL,
 kind TEXT NOT NULL, payload TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS roads (
 x INTEGER NOT NULL, y INTEGER NOT NULL, owner TEXT NOT NULL, created BIGINT NOT NULL,
 PRIMARY KEY(x,y)
);
CREATE TABLE IF NOT EXISTS wallets (account TEXT PRIMARY KEY, balance BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS ledger_tx (id TEXT PRIMARY KEY, kind TEXT NOT NULL, memo TEXT NOT NULL, created BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS ledger_entries (
 tx_id TEXT NOT NULL REFERENCES ledger_tx(id), account TEXT NOT NULL, amount BIGINT NOT NULL,
 PRIMARY KEY(tx_id, account)
);
CREATE TABLE IF NOT EXISTS world_clock (id INTEGER PRIMARY KEY, epoch BIGINT NOT NULL, month_seconds BIGINT NOT NULL, base_index BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS building_ops (object_id TEXT PRIMARY KEY, owner TEXT NOT NULL, kind TEXT NOT NULL, start_month BIGINT NOT NULL, start_permille INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS construction_stages (object_id TEXT PRIMARY KEY REFERENCES buildings(id) ON DELETE CASCADE, stage TEXT NOT NULL CHECK(stage IN ('foundation','frame','complete')), next_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS construction_stages_due ON construction_stages(next_at) WHERE stage != 'complete';
CREATE TABLE IF NOT EXISTS market_prices (product TEXT NOT NULL, month_index BIGINT NOT NULL, price BIGINT NOT NULL, supply BIGINT NOT NULL, demand BIGINT NOT NULL, PRIMARY KEY(product, month_index));
CREATE TABLE IF NOT EXISTS world_state (id INTEGER PRIMARY KEY, processed_through BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS inventory (owner TEXT NOT NULL, product TEXT NOT NULL, qty BIGINT NOT NULL, PRIMARY KEY(owner, product));
CREATE TABLE IF NOT EXISTS company_reports (owner TEXT NOT NULL, month_index BIGINT NOT NULL, revenue BIGINT NOT NULL, input_cost BIGINT NOT NULL, upkeep BIGINT NOT NULL, profit BIGINT NOT NULL, buildings INTEGER NOT NULL, PRIMARY KEY(owner, month_index));
CREATE TABLE IF NOT EXISTS population (month_index BIGINT PRIMARY KEY, population BIGINT NOT NULL, labor_force BIGINT NOT NULL, jobs BIGINT NOT NULL, wage BIGINT NOT NULL, staffing_permille INTEGER NOT NULL, demand_permille INTEGER NOT NULL, next_population BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS loans (owner TEXT PRIMARY KEY, balance BIGINT NOT NULL, interest_paid BIGINT NOT NULL, taken_total BIGINT NOT NULL, repaid_total BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS company_status (owner TEXT PRIMARY KEY, missed INTEGER NOT NULL, wages_owed BIGINT NOT NULL, input_owed BIGINT NOT NULL, maint_owed BIGINT NOT NULL, bankruptcies INTEGER NOT NULL, last_bankruptcy_month BIGINT, written_off BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS city_policy (id INTEGER PRIMARY KEY, profit_tax_permille INTEGER NOT NULL, property_tax_permille INTEGER NOT NULL, social_share_permille INTEGER NOT NULL, changed_month BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS company_tax_state (owner TEXT PRIMARY KEY, tax_owed BIGINT NOT NULL, vat_credit BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS company_taxes (owner TEXT NOT NULL, month_index BIGINT NOT NULL, vat BIGINT NOT NULL, profit_tax BIGINT NOT NULL, property_tax BIGINT NOT NULL, paid BIGINT NOT NULL, PRIMARY KEY(owner, month_index));
CREATE TABLE IF NOT EXISTS city_state (id INTEGER PRIMARY KEY, mayor TEXT NOT NULL, mayor_name TEXT NOT NULL, since_month BIGINT NOT NULL, term_end_month BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS mayor_rating (month_index BIGINT PRIMARY KEY, mayor TEXT NOT NULL, residents_permille INTEGER NOT NULL, business_permille INTEGER NOT NULL, total_permille INTEGER NOT NULL, low_streak INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS mayor_terms (mayor TEXT NOT NULL, name TEXT NOT NULL, from_month BIGINT NOT NULL, to_month BIGINT, reason TEXT, avg_rating_permille INTEGER, bonus BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(from_month, mayor));
CREATE TABLE IF NOT EXISTS election_candidates (election BIGINT NOT NULL, candidate TEXT NOT NULL, name TEXT NOT NULL, profit_permille INTEGER NOT NULL, property_permille INTEGER NOT NULL, social_permille INTEGER NOT NULL, slogan TEXT NOT NULL, PRIMARY KEY(election, candidate));
CREATE TABLE IF NOT EXISTS election_votes (election BIGINT NOT NULL, voter TEXT NOT NULL, candidate TEXT NOT NULL, PRIMARY KEY(election, voter));
CREATE TABLE IF NOT EXISTS election_results (election BIGINT PRIMARY KEY, winner TEXT NOT NULL, winner_name TEXT NOT NULL, tally TEXT NOT NULL, month_index BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS npc_state (owner TEXT PRIMARY KEY, acted_through BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS company_state (owner TEXT PRIMARY KEY, settled_through BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS monthly_reports (owner TEXT NOT NULL, month_index BIGINT NOT NULL, revenue BIGINT NOT NULL, upkeep BIGINT NOT NULL, profit BIGINT NOT NULL, buildings INTEGER NOT NULL, PRIMARY KEY(owner, month_index));
CREATE TABLE IF NOT EXISTS auth_attempts (attempt_key TEXT PRIMARY KEY, window_start BIGINT NOT NULL, attempts INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS auth_tokens (token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), purpose TEXT NOT NULL, expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS email_verified (user_id BIGINT PRIMARY KEY REFERENCES users(id), verified_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS commands (
 owner TEXT NOT NULL, request_id TEXT NOT NULL, response TEXT NOT NULL,
 PRIMARY KEY(owner,request_id)
);
CREATE TABLE IF NOT EXISTS trade_offers (
 id TEXT PRIMARY KEY, supplier TEXT NOT NULL, product TEXT NOT NULL, qty BIGINT NOT NULL,
 price BIGINT NOT NULL, term_months INTEGER NOT NULL, penalty BIGINT NOT NULL, status TEXT NOT NULL,
 created_month BIGINT NOT NULL, created BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS trade_contracts (
 id TEXT PRIMARY KEY, offer_id TEXT NOT NULL, supplier TEXT NOT NULL, buyer TEXT NOT NULL,
 product TEXT NOT NULL, qty BIGINT NOT NULL, price BIGINT NOT NULL, penalty BIGINT NOT NULL,
 start_month BIGINT NOT NULL, end_month BIGINT NOT NULL, status TEXT NOT NULL,
 closed_reason TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS trade_deliveries (
 contract_id TEXT NOT NULL, month_index BIGINT NOT NULL, delivered BIGINT NOT NULL,
 shortfall BIGINT NOT NULL, paid BIGINT NOT NULL, penalty_paid BIGINT NOT NULL,
 PRIMARY KEY(contract_id, month_index)
);
CREATE TABLE IF NOT EXISTS trade_debts (
 debtor TEXT NOT NULL, creditor TEXT NOT NULL, amount BIGINT NOT NULL,
 PRIMARY KEY(debtor, creditor)
);
CREATE TABLE IF NOT EXISTS eco_owner_spend (
 owner TEXT NOT NULL, month_index BIGINT NOT NULL, amount BIGINT NOT NULL,
 PRIMARY KEY(owner, month_index)
);
CREATE TABLE IF NOT EXISTS company_trucks (
 owner TEXT PRIMARY KEY, units INTEGER NOT NULL, capacity_each INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS truck_trips (
 id TEXT PRIMARY KEY, owner TEXT NOT NULL, origin TEXT NOT NULL, destination TEXT NOT NULL,
 product TEXT NOT NULL, qty BIGINT NOT NULL, trucks INTEGER NOT NULL,
 depart_month BIGINT NOT NULL, arrive_month BIGINT NOT NULL, status TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS company_research (
 id TEXT PRIMARY KEY, owner TEXT NOT NULL, track TEXT NOT NULL, cost BIGINT NOT NULL,
 start_month BIGINT NOT NULL, ready_month BIGINT NOT NULL, status TEXT NOT NULL
);
"""

def init():
    with connect() as db:
        for statement in SCHEMA.split(";"):
            if statement.strip():
                db.execute(statement)
        import social
        social.ensure(db, "%s")
        import admin_api
        admin_api.ensure(db, "%s", postgres=True)
        import citygen
        citygen.ensure(db, "%s")
        import regions
        regions.ensure(db, "%s")
        import deposits
        deposits.ensure(db, "%s")
        import zoning
        zoning.ensure(db, "%s")
        import terrain_edits
        terrain_edits.ensure(db)
        # BEGIN ChatGPT11 schema
        import holding
        holding.ensure(db, "%s")
        # END ChatGPT11 schema
        db.commit()