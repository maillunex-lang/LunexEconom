from pathlib import Path
from xml.sax.saxutils import escape

OUT = Path(__file__).resolve().parents[2] / "docs" / "mockups"
BG, S1, S2, S3 = "#0A201B", "#173A30", "#22483B", "#2E5A4B"
ACC, TXT, SEC, WARN, ERR, OK = "#B7EFA5", "#EEF5E8", "#A1B9AD", "#F2C14E", "#F28B82", "#7BD88F"


class Page:
    def __init__(self, title, nav):
        self.p = [f'<svg xmlns="http://www.w3.org/2000/svg" width="1920" height="1080" viewBox="0 0 1920 1080">',
                  f'<rect width="1920" height="1080" fill="{BG}"/>']
        self.rect(0, 0, 1920, 80, S1)
        self.text(40, 50, title, 22, TXT)
        self.text(1500, 50, "Баланс: 300 000 ₽ · Год 2027 · Месяц 2 · День 7", 16, ACC)
        self.rect(0, 980, 1920, 100, S2)
        for i, name in enumerate(["Штаб", "Карта", "Предприятия", "Финансы", "Ещё"]):
            self.text(200 + i * 360, 1040, name, 15, ACC if name == nav else TXT, "middle")

    def rect(self, x, y, w, h, fill, rx=0, stroke=None):
        s = f' stroke="{stroke}" stroke-width="2"' if stroke else ""
        self.p.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}"{s}/>')

    def text(self, x, y, t, size=16, fill=TXT, anchor="start", weight=None):
        w = f' font-weight="{weight}"' if weight else ""
        self.p.append(f'<text x="{x}" y="{y}" font-family="sans-serif" font-size="{size}" fill="{fill}" text-anchor="{anchor}"{w}>{escape(str(t))}</text>')

    def card(self, x, y, w, h, title=None):
        self.rect(x, y, w, h, S1, 18)
        if title:
            self.text(x + 24, y + 40, title, 20, ACC)

    def button(self, x, y, w, label, primary=False, h=56):
        self.rect(x, y, w, h, ACC if primary else S2, 12, None if primary else S3)
        self.text(x + w // 2, y + h // 2 + 6, label, 16, BG if primary else TXT, "middle")

    def bar(self, x, y, w, pct, label=None, color=OK, h=18):
        self.rect(x, y, w, h, BG, 9)
        self.rect(x, y, max(1, w * pct // 100), h, color, 9)
        if label:
            self.text(x, y - 8, label, 14, SEC)

    def row(self, x, y, cells, widths, color=TXT, size=15):
        for c, w in zip(cells, widths):
            self.text(x, y, c, size, color)
            x += w

    def save(self, name):
        OUT.mkdir(parents=True, exist_ok=True)
        (OUT / f"{name}_1920x1080.svg").write_text("\n".join(self.p + ["</svg>"]) + "\n", encoding="utf-8")


